create or replace function public.match_contents(
  query_embedding extensions.vector(384),
  match_count integer default 10,
  filter_content_type public.content_type default null,
  min_similarity double precision default 0
)
returns table (
  id bigint,
  title text,
  content_type public.content_type,
  overview text,
  poster_url text,
  rating_average numeric,
  similarity double precision
)
language sql
stable
security invoker
set search_path = ''
as $$
  select
    c.id,
    c.title,
    c.content_type,
    c.overview,
    c.poster_url,
    c.rating_average,
    1 - (c.embedding <=> query_embedding) as similarity
  from public.contents as c
  where c.is_active
    and c.embedding is not null
    and (filter_content_type is null or c.content_type = filter_content_type)
    and 1 - (c.embedding <=> query_embedding) >= coalesce(min_similarity, 0)
  order by c.embedding <=> query_embedding
  limit least(greatest(coalesce(match_count, 10), 1), 100);
$$;

comment on function public.match_contents(extensions.vector, integer, public.content_type, double precision) is
