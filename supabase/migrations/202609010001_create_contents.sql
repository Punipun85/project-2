-- EntertainmentAI unified content catalog for Supabase/PostgreSQL.
-- Embeddings use 384 dimensions to match the Sentence Transformer profile
-- used by this project. Change the dimension before applying this migration
-- if the production embedding model emits a different vector size.

begin;

create schema if not exists extensions;
create extension if not exists vector with schema extensions;
create extension if not exists pg_trgm with schema extensions;

do $$
begin
  create type public.content_type as enum (
    'movie',
    'anime',
    'kdrama',
    'tv_series',
    'documentary'
  );
exception
  when duplicate_object then null;
end
$$;

comment on type public.content_type is
  'Supported unified entertainment categories in EntertainmentAI.';

create table if not exists public.contents (
  id bigint generated by default as identity primary key,
  external_id text not null,
  source text not null,
  content_type public.content_type not null,

  title text not null,
  original_title text,
  alternative_titles jsonb not null default '[]'::jsonb,

  overview text,
  tagline text,

  genres jsonb not null default '[]'::jsonb,
  original_language varchar(16),
  country jsonb not null default '[]'::jsonb,

  release_date date,
  release_year integer,

  poster_url text,
  backdrop_url text,
  trailer_url text,

  duration_minutes integer,
  episodes integer,
  season_number integer,
  studio jsonb not null default '[]'::jsonb,
  network text,

  director jsonb not null default '[]'::jsonb,
  cast jsonb not null default '[]'::jsonb,
  characters jsonb not null default '[]'::jsonb,

  rating_average numeric(4, 2),
  rating_count integer not null default 0,
  imdb_rating numeric(4, 2),
  mal_rating numeric(4, 2),
  popularity_score numeric(12, 4) not null default 0,

  embedding extensions.vector(384),
  ai_summary text,
  ai_tags jsonb not null default '[]'::jsonb,
  themes jsonb not null default '[]'::jsonb,
  moods jsonb not null default '[]'::jsonb,

  search_document tsvector generated always as (
    setweight(to_tsvector('simple'::regconfig, coalesce(title, '')), 'A') ||
    setweight(to_tsvector('simple'::regconfig, coalesce(overview, '')), 'B') ||
    setweight(to_tsvector('simple'::regconfig, genres::text), 'B') ||
    setweight(to_tsvector('simple'::regconfig, themes::text), 'B')
  ) stored,

  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint contents_source_external_id_key unique (source, external_id),
  constraint contents_external_id_not_blank check (btrim(external_id) <> ''),
  constraint contents_source_not_blank check (btrim(source) <> ''),
  constraint contents_source_canonical_case check (source = upper(source)),
  constraint contents_title_not_blank check (btrim(title) <> ''),
  constraint contents_alternative_titles_array check (jsonb_typeof(alternative_titles) = 'array'),
  constraint contents_genres_array check (jsonb_typeof(genres) = 'array'),
  constraint contents_country_array check (jsonb_typeof(country) = 'array'),
  constraint contents_studio_array check (jsonb_typeof(studio) = 'array'),
  constraint contents_director_array check (jsonb_typeof(director) = 'array'),
  constraint contents_cast_array check (jsonb_typeof(cast) = 'array'),
  constraint contents_characters_array check (jsonb_typeof(characters) = 'array'),
  constraint contents_ai_tags_array check (jsonb_typeof(ai_tags) = 'array'),
  constraint contents_themes_array check (jsonb_typeof(themes) = 'array'),
  constraint contents_moods_array check (jsonb_typeof(moods) = 'array'),
  constraint contents_release_year_range check (release_year is null or release_year between 1800 and 2200),
  constraint contents_release_date_year_consistent check (
    release_date is null
    or release_year is null
    or release_year = extract(year from release_date)::integer
  ),
  constraint contents_duration_positive check (duration_minutes is null or duration_minutes > 0),
  constraint contents_episodes_nonnegative check (episodes is null or episodes >= 0),
  constraint contents_season_nonnegative check (season_number is null or season_number >= 0),
  constraint contents_rating_average_range check (rating_average is null or rating_average between 0 and 10),
  constraint contents_rating_count_nonnegative check (rating_count >= 0),
  constraint contents_imdb_rating_range check (imdb_rating is null or imdb_rating between 0 and 10),
  constraint contents_mal_rating_range check (mal_rating is null or mal_rating between 0 and 10),
  constraint contents_popularity_nonnegative check (popularity_score >= 0)
);

