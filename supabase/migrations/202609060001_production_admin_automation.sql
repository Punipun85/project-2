grant execute on function public.get_admin_dashboard() to authenticated, service_role;
revoke execute on function public.refresh_daily_analytics() from public, anon, authenticated;
grant execute on function public.refresh_daily_analytics() to service_role;
revoke execute on function public.cleanup_operational_history() from public, anon, authenticated;
grant execute on function public.cleanup_operational_history() to service_role;

commit;
